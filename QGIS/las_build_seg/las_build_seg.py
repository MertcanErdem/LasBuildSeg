    def extract_components_alpha(self, mask, gt, alpha):
        """
        NEW: Instead of one global alpha shape (which merges everything),
        label connected components first, then run alpha shape per component.
        This prevents vegetation patches from merging with buildings and
        gives much cleaner per-building polygons.
        """
        import numpy as np
        import alphashape
        from scipy.ndimage import label

        labeled, num_features = label(mask)
        geoms = []

        self.iface.messageBar().pushMessage(
            "LasBuildSeg",
            f"Found {num_features} raw connected components — running per-component alpha shape...",
            level=Qgis.Info
        )

        for comp_id in range(1, num_features + 1):
            comp_mask = labeled == comp_id
            rows, cols = np.where(comp_mask)

            if len(rows) < 4:
                continue  # too small to form a shape

            pts_x = gt[0] + (cols + 0.5) * gt[1]
            pts_y = gt[3] + (rows + 0.5) * gt[5]   # gt[5]>0, y increases northward
            pts = np.column_stack((pts_x, pts_y))

            try:
                shape = alphashape.alphashape(pts, alpha)
                if shape is None or shape.is_empty:
                    shape = alphashape.alphashape(pts, 0.0)

                if shape is None or shape.is_empty:
                    continue

                if shape.geom_type == 'Polygon':
                    geoms.append(shape)
                elif shape.geom_type == 'MultiPolygon':
                    geoms.extend(list(shape.geoms))
            except Exception:
                continue  # skip bad components silently

        return geoms

