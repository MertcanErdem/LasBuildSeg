    def calculate_global_tri(self, dsm_array, resolution=1.0):
        """Calculate Terrain Ruggedness Index (gradient magnitude)."""
        import numpy as np
        dy, dx = np.gradient(dsm_array)
        tri = np.sqrt(dx**2 + dy**2)
        tri /= resolution
        return tri

    def analyze_low_res_ndhm(self, ndhm_array, downscale_factor=3, ndhm_path=None):
        """
        Port of standalone analyze_low_res_ndhm.
        Uses GDAL ReadAsArray(buf_xsize, buf_ysize) for downsampling, which
        matches rasterio Resampling.average (GDAL average resampling under the hood).
        This is critical: numpy reshape+mean gives different statistics near void
        areas compared to rasterio's average resampling.
        """
        import numpy as np
        from osgeo import gdal

        self.iface.messageBar().pushMessage('LasBuildSeg',
            f'Analysing coarse-scale nDSM (downscale 1/{downscale_factor})…', level=Qgis.Info)

        if ndhm_path and os.path.exists(ndhm_path):
            # Read from disk using GDAL average resampling — matches rasterio Resampling.average
            ds = gdal.Open(ndhm_path)
            bnd = ds.GetRasterBand(1)
            full_w, full_h = ds.RasterXSize, ds.RasterYSize
            new_w = full_w // downscale_factor
            new_h = full_h // downscale_factor
            # GDAL ReadAsArray with buf_xsize/buf_ysize does average downsampling
            low_res_data = bnd.ReadAsArray(0, 0, full_w, full_h,
                                           buf_xsize=new_w, buf_ysize=new_h,
                                           resample_alg=gdal.GRIORA_Average)
            ds = None
        else:
            # Fallback: numpy average (less accurate near voids)
            h, w = ndhm_array.shape
            new_h = h // downscale_factor; new_w = w // downscale_factor
            arr = ndhm_array[:new_h*downscale_factor, :new_w*downscale_factor]
            low_res_data = arr.reshape(new_h, downscale_factor, new_w, downscale_factor).mean(axis=(1,3))

        potential_buildings = low_res_data[low_res_data > 2.5]
        avg_height = np.mean(potential_buildings) if potential_buildings.size > 0 else 5.0

        gy, gx = np.gradient(low_res_data)
        slope = np.sqrt(gx**2 + gy**2)
        potential_slopes = slope[low_res_data > 2.5]
        avg_slope = np.percentile(potential_slopes, 85) if potential_slopes.size > 0 else 1.0

        alphashape_height_thresh = avg_height * 0.4
        if alphashape_height_thresh < 2.0: alphashape_height_thresh = 2.0
        filter_height_thresh = alphashape_height_thresh * 0.8
        adaptive_tri_thresh = avg_slope * 0.75
        if adaptive_tri_thresh < 1.0: adaptive_tri_thresh = 1.0

        self.iface.messageBar().pushMessage('Adaptive Thresholds',
            f'AlphaShape Height={alphashape_height_thresh:.2f}, '
            f'Filter Height={filter_height_thresh:.2f} (80%), TRI={adaptive_tri_thresh:.2f}',
            level=Qgis.Info)
        return alphashape_height_thresh, filter_height_thresh, adaptive_tri_thresh

    def get_geometry_stats(self, geom):
        """Calculate area, squareness, and width"""
        import numpy as np
        
        area = geom.area()
        if area == 0: return 0, 0, 0
        
        ombb_res = geom.orientedMinimumBoundingBox()
        ombb = ombb_res[0] if isinstance(ombb_res, tuple) else ombb_res
        
        poly = ombb.asPolygon()
        if not poly: return area, 0, 0
        ring = poly[0]
        
        d1 = np.sqrt((ring[0].x()-ring[1].x())**2 + (ring[0].y()-ring[1].y())**2)
        d2 = np.sqrt((ring[1].x()-ring[2].x())**2 + (ring[1].y()-ring[2].y())**2)
        
        width = min(d1, d2)
        bbox_area = d1 * d2
        sq = area / bbox_area if bbox_area > 0 else 0
        
        return area, sq, width

    def calculate_exact_masked_tri(self, geom, tri_map, ndhm_map, gt, filter_h_thresh):
        import numpy as np
        try:
            bbox=geom.boundingBox(); x0,rx,y0,ry=gt[0],gt[1],gt[3],gt[5]
            c0=max(0,int((bbox.xMinimum()-x0)/rx)); c1=min(tri_map.shape[1],int((bbox.xMaximum()-x0)/rx)+1)
            r0=max(0,int((bbox.yMinimum()-y0)/ry)); r1=min(tri_map.shape[0],int((bbox.yMaximum()-y0)/ry)+1)
            if r0>=r1 or c0>=c1: return 0.0
            s=0.0; n=0
            for r in range(r0,r1):
                for c in range(c0,c1):
                    if ndhm_map[r,c]>filter_h_thresh:
                        if geom.contains(QgsPointXY(x0+(c+0.5)*rx, y0+(r+0.5)*ry)):
                            v=tri_map[r,c]
                            if not np.isnan(v): s+=v; n+=1
            return s/n if n>0 else 0.0
        except: return 0.0

