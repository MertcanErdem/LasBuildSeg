    def get_pdal_exe(self):
        pdal_exe = r"C:\Program Files\QGIS 3.44.1\bin\pdal.exe"
        if os.path.exists(pdal_exe): return pdal_exe
        pdal_exe = os.path.join(QgsApplication.prefixPath(), "bin", "pdal.exe")
