    def run_pdal_pipeline(self, pipeline_json):
        pdal_exe = self.get_pdal_exe()
        env = os.environ.copy()
        qgis_root = QgsApplication.prefixPath()
        proj_candidates = [
            os.path.join(qgis_root, "share", "proj"),
            os.path.join(qgis_root, "..", "share", "proj")
        ]
        for p in proj_candidates:
            if os.path.exists(os.path.join(p, "proj.db")):
                env["PROJ_LIB"] = p
                break
        
        cmd = [pdal_exe, "pipeline", "--stdin"]
        
        startupinfo = None
        if sys.platform == "win32":
            startupinfo = subprocess.STARTUPINFO()
            startupinfo.dwFlags |= subprocess.STARTF_USESHOWWINDOW
            startupinfo.wShowWindow = subprocess.SW_HIDE
        
        # Log the pipeline for debugging
        try:
            pipeline_dict = json.loads(pipeline_json)
            QgsMessageLog.logMessage(f"PDAL Pipeline: {json.dumps(pipeline_dict, indent=2)}", "LasBuildSeg", level=Qgis.Info)
        except:
            pass
        
        process = subprocess.run(
            cmd, 
            input=pipeline_json.encode('utf-8'), 
            env=env, 
            stdout=subprocess.PIPE, 
            stderr=subprocess.PIPE, 
            startupinfo=startupinfo,
            cwd=os.getcwd()
        )
        
        if process.returncode != 0:
            error_msg = process.stderr.decode()
            if "Permission denied" in error_msg:
                raise Exception(
                    f"PDAL Permission Error:\n{error_msg}\n\n"
                    f"Try:\n"
                    f"1. Select a different output folder with write permissions\n"
                    f"2. Run QGIS as administrator\n"
                    f"3. Check if output files are open in another program"
                )
            else:
                raise Exception(f"PDAL Error: {error_msg}")
        
        return process.stdout.decode()

