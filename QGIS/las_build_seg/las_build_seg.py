    def laz_pre_analysis(self, laz_path):
        """Port of standalone laz_pre_analysis — uses all-return count + all-return slope."""
        import numpy as np
        pdal_exe = self.get_pdal_exe()
        env = os.environ.copy()
        si = None
        if sys.platform == 'win32':
            si = subprocess.STARTUPINFO()
            si.dwFlags |= subprocess.STARTF_USESHOWWINDOW
            si.wShowWindow = subprocess.SW_HIDE
        r = subprocess.run([pdal_exe, 'info', '--metadata', laz_path],
            capture_output=True, text=True, timeout=120, env=env, startupinfo=si)
        meta = json.loads(r.stdout).get('metadata', {})
        total = int(meta.get('count', 0))
        area  = (float(meta.get('maxx',0)) - float(meta.get('minx',0))) * \
                (float(meta.get('maxy',0)) - float(meta.get('miny',0)))
        point_density = total / area if area > 0 else 10.0

        # All-returns decimated sample for slope (no filters.returns — matches las.x/y/z)
        step = max(1, total // 500_000)
        tmp = laz_path.replace('.laz','_ana.txt').replace('.las','_ana.txt')
        self.run_pdal_pipeline(json.dumps({'pipeline': [laz_path,
            {'type':'filters.decimation','step':step},
            {'type':'writers.text','filename':tmp,'order':'X,Y,Z',
             'keep_unspecified':'false','delimiter':',','write_header':False}]}))
        pts = np.loadtxt(tmp, delimiter=',', dtype=np.float32)
        if os.path.exists(tmp): os.remove(tmp)

        c,_,_,_ = np.linalg.lstsq(
            np.column_stack((pts[:,0], pts[:,1], np.ones(len(pts)))), pts[:,2], rcond=None)
        slope = math.sqrt(c[0]**2 + c[1]**2)
        cloth_res = 0.5 if point_density>15 else (1.0 if point_density>5 else 2.0)
        rigidness = 1 if slope>0.3 else (2 if slope>0.1 else 3)
        self.iface.messageBar().pushMessage('LasBuildSeg',
            f'density={point_density:.2f} slope={slope:.4f} → CSF res={cloth_res} rigid={rigidness}',
            level=Qgis.Info)
        return {'cloth_resolution': cloth_res, 'rigidness': rigidness, 'class_threshold': 0.1}

    # =========================================================================
    # 2. GENERATION (DSM / DTM) - USING LAST RETURNS
    # =========================================================================
    def generate_dsm_pdal(self, laz_path, out_path, resolution=1.0):
        """
        Port of standalone generate_dsm_last_returns.
        griddata(nearest), void masking, bottom-up orientation (positive Y step),
        CRS read from PDAL output (VLR binary records), returns detected EPSG.
        """
        import numpy as np, scipy.interpolate
        from osgeo import gdal, osr
        from scipy.ndimage import maximum_filter

        tmp = laz_path.replace('.laz','_dsm.txt').replace('.las','_dsm.txt')
        self.run_pdal_pipeline(json.dumps({'pipeline': [laz_path,
            {'type':'filters.returns','groups':'last,only'},
            {'type':'writers.text','filename':tmp,'order':'X,Y,Z',
             'keep_unspecified':'false','delimiter':',','write_header':False}]}))
        pts = np.loadtxt(tmp, delimiter=',', dtype=np.float64)
        if os.path.exists(tmp): os.remove(tmp)

        x, y, z = pts[:,0], pts[:,1], pts[:,2]
        x_min = float(np.floor(x.min())); x_max = float(np.ceil(x.max()))
        y_min = float(np.floor(y.min())); y_max = float(np.ceil(y.max()))

        # Exactly matches standalone: arange(x_min,x_max,res) × arange(y_min,y_max,res)
        # row 0 = southernmost (Affine(res,0,x_min,0,res,y_min) convention)
        gx, gy = np.meshgrid(np.arange(x_min, x_max, resolution),
                              np.arange(y_min, y_max, resolution))
        nr, nc = gx.shape
        dsm = scipy.interpolate.griddata((x,y), z, (gx,gy), method='nearest').astype(np.float32)

        # Void masking — same as standalone maximum_filter approach
        ci = np.clip(((x-x_min)/resolution).astype(int), 0, nc-1)
        ri = np.clip(((y-y_min)/resolution).astype(int), 0, nr-1)
        cnt = np.zeros((nr,nc), dtype=np.int32)
        np.add.at(cnt, (ri,ci), 1)
        dsm[~maximum_filter(cnt>0, size=3)] = np.float32(-9999)
        dsm = np.where(np.isnan(dsm), np.float32(-9999), dsm)

        # Bottom-up geotransform — positive Y step, row 0 = south
        gt = (x_min, resolution, 0.0, y_min, 0.0, resolution)
        self._dsm_gt = gt; self._dsm_shape = (nr, nc)

        # CRS from PDAL (reads binary VLR records that pdal info --metadata often misses)
        proj_wkt = ''
        try:
            ctmp = out_path + '_crs.tif'
            self.run_pdal_pipeline(json.dumps({'pipeline': [laz_path,
                {'type':'filters.head','count':1},
                {'type':'writers.gdal','filename':ctmp,'resolution':resolution,
                 'output_type':'max','data_type':'float','nodata':-9999}]}))
            _ds = gdal.Open(ctmp)
            if _ds: proj_wkt = _ds.GetProjection() or ''; _ds = None
            if os.path.exists(ctmp): os.remove(ctmp)
        except Exception as e:
            QgsMessageLog.logMessage(f'CRS probe: {e}','LasBuildSeg',level=Qgis.Warning)
        self._dsm_proj_wkt = proj_wkt

        drv = gdal.GetDriverByName('GTiff')
        ds = drv.Create(out_path, nc, nr, 1, gdal.GDT_Float32)
        ds.SetGeoTransform(gt)
        if proj_wkt: ds.SetProjection(proj_wkt)
        bnd = ds.GetRasterBand(1); bnd.SetNoDataValue(-9999); bnd.WriteArray(dsm)
        ds.FlushCache(); ds = None

        epsg = 0
        if proj_wkt:
            try:
                s = osr.SpatialReference(); s.ImportFromWkt(proj_wkt)
                c = s.GetAuthorityCode(None)
                if c and str(c).isdigit(): epsg = int(c)
            except Exception: pass
        if epsg:
            self.iface.messageBar().pushMessage('LasBuildSeg',f'CRS: EPSG:{epsg}',level=Qgis.Info)
        return epsg

    def generate_dtm_csf_pdal(self, laz_path, reference_dsm_path, csf_params):
        """
        Port of standalone generate_dtm_with_csf_last_returns.
        Uses linspace grid matching DSM bounds (same as standalone).
        Same bottom-up orientation as DSM — no alignment needed.
        """
        import numpy as np, scipy.interpolate, CSF
        from osgeo import gdal

        gt = getattr(self,'_dsm_gt',None); shape = getattr(self,'_dsm_shape',None)
        proj_wkt = getattr(self,'_dsm_proj_wkt','')
        if gt is None:
            _ds = gdal.Open(reference_dsm_path)
            gt = _ds.GetGeoTransform(); shape = (_ds.RasterYSize, _ds.RasterXSize)
            proj_wkt = _ds.GetProjection(); _ds = None

        nr, nc = shape; x0, rx, _, y0, _, ry = gt  # ry > 0 (south-up)

        # Exact port: x=linspace(bounds.left,bounds.right,width), y=linspace(bounds.bottom,bounds.top,height)
        # bounds.left=x0, bounds.right=x0+nc*rx, bounds.bottom=y0, bounds.top=y0+nr*ry
        gx, gy = np.meshgrid(np.linspace(x0, x0+nc*rx, nc),
                              np.linspace(y0, y0+nr*ry, nr))   # row 0 = south

        tmp = laz_path.replace('.laz','_dtm.txt').replace('.las','_dtm.txt')
        self.run_pdal_pipeline(json.dumps({'pipeline': [laz_path,
            {'type':'filters.returns','groups':'last,only'},
            {'type':'writers.text','filename':tmp,'order':'X,Y,Z',
             'keep_unspecified':'false','delimiter':',','write_header':False}]}))
        pts = np.loadtxt(tmp, delimiter=',', dtype=np.float64)
        if os.path.exists(tmp): os.remove(tmp)

        csf = CSF.CSF(); csf.params.bSloopSmooth = True
        csf.params.cloth_resolution = csf_params.get('cloth_resolution', 1.0)
        csf.params.rigidness        = csf_params.get('rigidness', 3)
        csf.params.class_threshold  = csf_params.get('class_threshold', 0.1)
        csf.setPointCloud(pts)
        gi = CSF.VecInt(); ngi = CSF.VecInt(); csf.do_filtering(gi, ngi)
        gp = pts[list(gi)]

        dtm = scipy.interpolate.griddata(
            (gp[:,0],gp[:,1]), gp[:,2], (gx,gy), method='nearest').astype(np.float32)
        return dtm, gt, proj_wkt

