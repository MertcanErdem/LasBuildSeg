    def calculate_height_variance(self, geom, ndhm, gt, filter_h_thresh):
        import numpy as np
        try:
            bbox=geom.boundingBox(); x0,rx,y0,ry=gt[0],gt[1],gt[3],gt[5]
            c0=max(0,int((bbox.xMinimum()-x0)/rx)); c1=min(ndhm.shape[1],int((bbox.xMaximum()-x0)/rx)+1)
            r0=max(0,int((bbox.yMinimum()-y0)/ry)); r1=min(ndhm.shape[0],int((bbox.yMaximum()-y0)/ry)+1)
            if r0>=r1 or c0>=c1: return 0.0
            h=[]
            for r in range(r0,r1):
                for c in range(c0,c1):
                    if ndhm[r,c]>filter_h_thresh:
                        if geom.contains(QgsPointXY(x0+(c+0.5)*rx, y0+(r+0.5)*ry)):
                            h.append(ndhm[r,c])
            return float(np.std(h)) if len(h)>=3 else 0.0
        except: return 0.0

    def calculate_convex_hull_ratio(self, geom):
        """
        NEW: Convex hull ratio = polygon area / convex hull area.
        Buildings are convex-ish (ratio near 1.0). Trees and irregular
        vegetation blobs are often concave and branchy (lower ratio).
        A very low ratio (e.g. < 0.5) usually indicates non-building.
        """
        try:
            hull = geom.convexHull()
            hull_area = hull.area()
            if hull_area == 0:
                return 0.0
            return geom.area() / hull_area
        except Exception:
            return 0.0

    def calculate_elongation(self, geom):
        """
        NEW: Elongation = max_side / min_side from the oriented bounding box.
        Very elongated shapes (ratio >> 1) are roads, power lines, walls —
        not buildings. Buildings typically have elongation < 5–6.
        """
        try:
            ombb_res = geom.orientedMinimumBoundingBox()
            ombb = ombb_res[0] if isinstance(ombb_res, tuple) else ombb_res
            poly = ombb.asPolygon()
            if not poly:
                return 1.0
            ring = poly[0]
            import numpy as np
            d1 = math.sqrt((ring[0].x() - ring[1].x())**2 + (ring[0].y() - ring[1].y())**2)
            d2 = math.sqrt((ring[1].x() - ring[2].x())**2 + (ring[1].y() - ring[2].y())**2)
            if min(d1, d2) == 0:
                return 1.0
            return max(d1, d2) / min(d1, d2)
        except Exception:
            return 1.0

    def extract_and_filter(self, ndhm, dsm, gt, crs_wkt, alpha, alphashape_h_thresh,
                           filter_h_thresh, tri_thresh, min_size, max_size, sq_thresh,
                           w_thresh, kernel_size, out_path,
                           height_var_thresh=2.5,
                           convex_hull_ratio_min=0.5,
                           max_elongation=8.0,
                           use_per_component=True,
                           epsg_code=None):
        """
        Extract and filter buildings with TWO-STAGE thresholds + advanced
        false-positive elimination.

        alphashape_h_thresh : 100% height threshold — used for initial mask.
        filter_h_thresh     : 80% height threshold — used for TRI + variance calc.

        NEW FILTERS (all optional — set to 0/999 to disable):
        height_var_thresh   : Max allowed height std-dev inside polygon.
                              Buildings = flat roofs (low). Trees = high. Default 2.5m.
                              Set 0 to disable.
        convex_hull_ratio_min : Min ratio polygon_area / convex_hull_area.
                              Very branchy/concave shapes dropped. Default 0.5.
                              Set 0 to disable.
        max_elongation      : Maximum length/width ratio from OBB.
                              Drop power lines / walls. Default 8.0.
                              Set 999 to disable.
        use_per_component   : If True, run alpha shape per connected component
                              instead of one global shape. Default True.
        """
        import numpy as np
        import alphashape
        from scipy.ndimage import binary_opening

        # ---- 1. INITIAL MASK (alphashape threshold) ----
        mask_raw = ndhm > alphashape_h_thresh

        # ---- 2. MORPHOLOGICAL OPENING (pre-alpha noise removal) ----
        if kernel_size > 0:
            self.iface.messageBar().pushMessage(
                "LasBuildSeg",
                f"Pre-Alpha Morphological Opening (kernel={kernel_size})...",
                level=Qgis.Info
            )
            structure = np.ones((kernel_size, kernel_size))
            mask = binary_opening(mask_raw, structure=structure)
            removed = int(np.sum(mask_raw)) - int(np.sum(mask))
            self.iface.messageBar().pushMessage(
                "Noise Removal",
                f"Removed {removed} noisy pixels via morphological opening",
                level=Qgis.Info
            )

            # ---- FXAA-style edge-smoothing (matches standalone adaptiveparams.py) ----
            # Replicates cv2.Sobel + cv2.GaussianBlur using scipy so no new libraries needed.
            from scipy.ndimage import sobel as _sobel, gaussian_filter as _gblur
            _img = mask.astype(np.float32)
            _gx = _sobel(_img, axis=1)
            _gy = _sobel(_img, axis=0)
            _edge = np.sqrt(_gx ** 2 + _gy ** 2)
            _edge /= (_edge.max() + 1e-6)
            _blurred = _gblur(_img, sigma=1.0)          # sigma≈1 ≈ GaussianBlur(3,3,0)
            _blend = 0.8                                 # same blend_strength as standalone
            _result = _img * (1 - _blend * _edge) + _blurred * (_blend * _edge)
            mask = (_result > 0.5).astype(np.uint8)
            self.iface.messageBar().pushMessage(
                "LasBuildSeg", "Applied FXAA-style edge smoothing to mask", level=Qgis.Info
            )
        else:
            mask = mask_raw

        rows, cols = np.where(mask)
        if len(rows) < 4:
            self.iface.messageBar().pushMessage(
                "Warning", "No pixels found after morphological opening.", level=Qgis.Warning
            )
            return

        # ---- 3. ALPHA SHAPE EXTRACTION ----
        if use_per_component:
            # NEW: Per-connected-component approach — much fewer merged blobs
            geoms = self.extract_components_alpha(mask, gt, alpha)
        else:
            # Legacy: single global alpha shape
            pts_x = gt[0] + (cols + 0.5) * gt[1]
            pts_y = gt[3] + (rows + 0.5) * gt[5]
            pts = np.unique(np.column_stack((pts_x, pts_y)), axis=0)
            try:
                self.iface.messageBar().pushMessage(
                    "LasBuildSeg", f"Generating global Alpha Shape (alpha={alpha})...", level=Qgis.Info
                )
                shape = alphashape.alphashape(pts, alpha)
                if shape.is_empty:
                    shape = alphashape.alphashape(pts, 0.2)
                if shape.is_empty:
                    shape = alphashape.alphashape(pts, 0.0)
            except Exception as e:
                self.iface.messageBar().pushMessage("Error", f"AlphaShape failed: {e}", level=Qgis.Critical)
                return
            geoms = []
            if shape.geom_type == 'Polygon':
                geoms.append(shape)
            elif shape.geom_type == 'MultiPolygon':
                geoms.extend(list(shape.geoms))

        # ---- 4. REPROJECTION ─ GDAL OSR OAMS_TRADITIONAL_GIS_ORDER ----
        from osgeo import ogr as _ogr, osr as _osr
        _out_epsg = 0
        if epsg_code and int(epsg_code) > 0:
            try:
                _s=_osr.SpatialReference(); _s.ImportFromEPSG(int(epsg_code))
                _s.SetAxisMappingStrategy(_osr.OAMS_TRADITIONAL_GIS_ORDER)
                _d=_osr.SpatialReference(); _d.ImportFromEPSG(3857)
                _d.SetAxisMappingStrategy(_osr.OAMS_TRADITIONAL_GIS_ORDER)
                _ct=_osr.CoordinateTransformation(_s,_d); _out_epsg=3857
                def _reproject_geom(sg):
                    og=_ogr.CreateGeometryFromWkt(sg.wkt); og.Transform(_ct)
                    return QgsGeometry.fromWkt(og.ExportToWkt())
                self.iface.messageBar().pushMessage('LasBuildSeg',
                    f'Reprojecting EPSG:{epsg_code} → EPSG:3857', level=Qgis.Info)
            except Exception as ex:
                QgsMessageLog.logMessage(f'Reproject:{ex}','LasBuildSeg',level=Qgis.Warning)
                epsg_code=0
        if not epsg_code or int(epsg_code)<=0:
            _out_epsg=0
            def _reproject_geom(sg): return QgsGeometry.fromWkt(sg.wkt)
            self.iface.messageBar().pushMessage('LasBuildSeg',
                'No EPSG — output in source coords. Set Input CRS in dialog.',level=Qgis.Warning)
        _crs_str = f'crs=EPSG:{_out_epsg}' if _out_epsg else 'crs='

        def _remove_layer_if_open(path):
            """
            Remove any QGIS layer currently pointing to this file path.
            Without this, writing to a file that's open as a QGIS layer either
            fails silently (Windows file lock) or writes but QGIS keeps showing
            the old cached version — making it look like parameters have no effect.
            """
            path_norm = os.path.normcase(os.path.abspath(path))
            to_remove = []
            for layer_id, layer in QgsProject.instance().mapLayers().items():
                try:
                    src = os.path.normcase(os.path.abspath(layer.source().split("|")[0]))
                    if src == path_norm:
                        to_remove.append(layer_id)
                except Exception:
                    pass
            if to_remove:
                QgsProject.instance().removeMapLayers(to_remove)

        def _write_geojson(layer, path):
            _remove_layer_if_open(path)
            opts = QgsVectorFileWriter.SaveVectorOptions()
            opts.driverName = "GeoJSON"
            opts.fileEncoding = "UTF-8"
            QgsVectorFileWriter.writeAsVectorFormatV2(
                layer, path, QgsCoordinateTransformContext(), opts
            )

        # ---- 5. SAVE DEBUG CANDIDATES (in 3857) ----
        debug_path = out_path.replace(".geojson", "_debug_candidates.geojson")
        debug_layer = QgsVectorLayer(f"Polygon?{_crs_str}", "Debug", "memory")
        dpr = debug_layer.dataProvider()
        dfeat = QgsFeature()
        for g in geoms:
            dfeat.setGeometry(_reproject_geom(g))
            dpr.addFeatures([dfeat])
        _write_geojson(debug_layer, debug_path)
        QgsProject.instance().addMapLayer(QgsVectorLayer(debug_path, "Debug Candidates", "ogr"))

        # ---- 6. GLOBAL TRI MAP ----
        tri_map = self.calculate_global_tri(dsm, abs(gt[1]))

        # ---- 7. MULTI-FILTER PASS ----
        # Note: geometry stats (area, width, squareness) are computed in the
        # SOURCE CRS before reprojection so pixel-space measurements stay accurate.
        # The geometry added to the output layer is the reprojected 3857 version.
        layer = QgsVectorLayer(f"Polygon?{_crs_str}", "Buildings", "memory")
        pr = layer.dataProvider()
        pr.addAttributes([
            QgsField("Area",           QVariant.Double),
            QgsField("Squareness",     QVariant.Double),
            QgsField("Width",          QVariant.Double),
            QgsField("TRI",            QVariant.Double),
            QgsField("HeightVar",      QVariant.Double),
            QgsField("ConvexRatio",    QVariant.Double),
            QgsField("Elongation",     QVariant.Double),
        ])
        layer.updateFields()

        valid_features = []
        dropped = {
            'area': 0, 'sq': 0, 'tri': 0, 'width': 0,
            'height_var': 0, 'convex': 0, 'elongation': 0
        }

        for g in geoms:
            # Stats computed in native (source) CRS — accurate pixel measurements
            qgs_geom_src = QgsGeometry.fromWkt(g.wkt)

            # Size/shape stats computed on 3857 geometry (sq meters, meters).
            # Standalone filter_contours operates on the 3857-rasterized image,
            # so min_size=50 means 50 sq meters not 50 sq feet.
            # Without this, min_size is in sq feet (10x too permissive for US Survey Feet data).
            if _out_epsg == 3857:
                qgs_geom_metric = _reproject_geom(g)
            else:
                qgs_geom_metric = qgs_geom_src   # fallback if no reprojection

            area, sq, width = self.get_geometry_stats(qgs_geom_metric)

            if not (min_size <= area <= max_size):
                dropped['area'] += 1
                continue
            if sq < sq_thresh:
                dropped['sq'] += 1
                continue
            if width < w_thresh:
                dropped['width'] += 1
                continue

            elongation = self.calculate_elongation(qgs_geom_src)
            if elongation > max_elongation:
                dropped['elongation'] += 1
                continue

            cvx_ratio = self.calculate_convex_hull_ratio(qgs_geom_src)
            if cvx_ratio < convex_hull_ratio_min:
                dropped['convex'] += 1
                continue

            tri_val = self.calculate_exact_masked_tri(qgs_geom_src, tri_map, ndhm, gt, filter_h_thresh)
            if tri_val > tri_thresh:
                dropped['tri'] += 1
                continue

            h_var = self.calculate_height_variance(qgs_geom_src, ndhm, gt, filter_h_thresh)
            if height_var_thresh > 0 and h_var > height_var_thresh:
                dropped['height_var'] += 1
                continue

            # Passed all filters — reproject to 3857 for output
            feat = QgsFeature()
            feat.setGeometry(_reproject_geom(g))
            feat.setAttributes([area, sq, width, tri_val, h_var, cvx_ratio, elongation])
            valid_features.append(feat)

        self.iface.messageBar().pushMessage(
            "Filtering Stats",
            (f"Kept={len(valid_features)} | Dropped: "
             f"Area={dropped['area']}, Sq={dropped['sq']}, Width={dropped['width']}, "
             f"TRI={dropped['tri']}, HeightVar={dropped['height_var']}, "
             f"Convex={dropped['convex']}, Elong={dropped['elongation']}"),
            level=Qgis.Info
        )

        if valid_features:
            pr.addFeatures(valid_features)
            layer.updateExtents()
            _write_geojson(layer, out_path)
            QgsProject.instance().addMapLayer(QgsVectorLayer(out_path, "Filtered Buildings", "ogr"))
            self.iface.messageBar().pushMessage(
                "Success",
                f"Saved {len(valid_features)} buildings to {os.path.basename(out_path)}",
                level=Qgis.Success
            )
        else:
            self.iface.messageBar().pushMessage(
                "Warning",
                "All buildings were filtered out. Check the Debug Candidates layer and loosen parameters.",
                level=Qgis.Warning
            )

    # =========================================================================
    # MAIN EXECUTION
    # =========================================================================
    def run_logic(self):
        # Re-entrancy guard — processEvents() inside the progress bar can fire
        # this slot again if the user double-clicks Run or Qt drains the queue.
        if self._running:
            return
        self._running = True
        try:
            self._run_logic_inner()
        finally:
            self._running = False

    def _run_logic_inner(self):
        # Check dependencies first
        if not self.check_dependencies():
            return
        
        # Now import
        import numpy as np
        from osgeo import gdal
        
        if not hasattr(self.dlg, 'mQgsFileWidget_laz'): 
            return
            
        laz_path = self.dlg.mQgsFileWidget_laz.filePath()
        
        # Validate input file
        if not laz_path or not os.path.exists(laz_path):
            QMessageBox.warning(
                self.iface.mainWindow(),
                "Invalid Input",
                "Please select a valid LAS/LAZ file."
            )
            return
        
        # Get absolute path for input
        laz_path = os.path.abspath(laz_path)
        
        # Determine output directory
        if hasattr(self.dlg, 'lineEdit_Output') and self.dlg.lineEdit_Output.text():
            out_dir = self.dlg.lineEdit_Output.text()
        else:
            out_dir = os.path.dirname(laz_path)
        
        # Convert to absolute path
        out_dir = os.path.abspath(out_dir)
        
        # Create output directory if it doesn't exist
        if not os.path.exists(out_dir):
            try:
                os.makedirs(out_dir)
            except Exception as e:
                QMessageBox.critical(
                    self.iface.mainWindow(),
                    "Directory Error",
                    f"Cannot create output directory:\n{out_dir}\n\nError: {str(e)}"
                )
                return
        
        # Check write permissions
        if not os.access(out_dir, os.W_OK):
            QMessageBox.critical(
                self.iface.mainWindow(),
                "Permission Error",
                f"No write permission for output directory:\n{out_dir}\n\n"
                f"Please select a different output folder or run QGIS as administrator."
            )
            return

        # ---- Read core parameters from dialog ----
        RESOLUTION    = float(self.dlg.get_param('resolution',  1.0))
        EPSG_CODE     = int(self.dlg.get_param('epsg_code',    0))
        ALPHA_VAL     = self.dlg.get_param('alpha',          0.7)
        MIN_SIZE     = self.dlg.get_param('min_size',       100)
        MAX_SIZE     = self.dlg.get_param('max_size',       50000)
        SQUARE_THRESH = self.dlg.get_param('squareness',    0.3)
        WIDTH_THRESH  = self.dlg.get_param('width',         3.0)
        KERNEL_SIZE   = self.dlg.get_param('kernel_size',   7)

        # ---- Read NEW false-positive filter params from dialog ----
        HEIGHT_VAR_THRESH      = self.dlg.get_param('height_var_thresh',      2.5)
        CONVEX_HULL_RATIO_MIN  = self.dlg.get_param('convex_hull_ratio_min',  0.5)
        MAX_ELONGATION         = self.dlg.get_param('max_elongation',         8.0)
        USE_PER_COMPONENT      = self.dlg.get_param('use_per_component',      True)
        SKIP_RASTERS           = self.dlg.get_param('skip_rasters',           False)

        try:
            dsm_path  = os.path.join(out_dir, "dsm.tif")
            dtm_path  = os.path.join(out_dir, "dtm.tif")
            ndhm_path = os.path.join(out_dir, "ndhmtemp.tif")

            # ---- Progress bar setup ----
            total_steps = 4 if SKIP_RASTERS else 7
            progress = QProgressDialog("Initialising…", "Cancel", 0, total_steps, self.iface.mainWindow())
            progress.setWindowTitle("LasBuildSeg")
            progress.setWindowModality(Qt.WindowModal)
            progress.setMinimumWidth(420)
            progress.setValue(0)
            progress.show()

            def step(n, label):
                progress.setValue(n)
                progress.setLabelText(label)
                # Force the GUI to repaint so the label actually updates
                from qgis.PyQt.QtWidgets import QApplication
                QApplication.processEvents()
                if progress.wasCanceled():
                    raise Exception("Processing cancelled by user.")

            if SKIP_RASTERS:
                missing = [p for p in [dsm_path, dtm_path, ndhm_path]
                           if not os.path.exists(p)]
                if missing:
                    progress.close()
                    QMessageBox.critical(
                        self.iface.mainWindow(),
                        "Missing Raster Files",
                        "Cannot skip raster generation — these files are missing:\n\n"
                        + "\n".join(f"  • {os.path.basename(p)}" for p in missing)
                        + "\n\nUncheck 'Skip DSM/DTM/nDHM generation' and run again."
                    )
                    return

                step(1, "Loading existing DSM / nDHM…")
                ds = gdal.Open(dsm_path)
                dsm_array = ds.GetRasterBand(1).ReadAsArray()
                gt        = ds.GetGeoTransform()
                proj_wkt  = ds.GetProjection()
                ds = None
                if not EPSG_CODE and proj_wkt:
                    try:
                        from osgeo import osr as _o; _s=_o.SpatialReference()
                        _s.ImportFromWkt(proj_wkt); _c=_s.GetAuthorityCode(None)
                        if _c and str(_c).isdigit(): EPSG_CODE=int(_c)
                    except Exception: pass

                ds = gdal.Open(ndhm_path)
                ndhm = ds.GetRasterBand(1).ReadAsArray().astype(np.float32)
                ds = None
                # Keep raw values from ndhmtemp.tif — same as standalone

            else:
                step(1, "Step 1/7 — Analysing LAZ file…")
                csf_params = self.laz_pre_analysis(laz_path)

                step(2, "Step 2/7 — Generating DSM (griddata nearest)…")
                auto_epsg = self.generate_dsm_pdal(laz_path, dsm_path, resolution=RESOLUTION)
                if not EPSG_CODE and auto_epsg: EPSG_CODE = auto_epsg

                step(3, "Step 3/7 — Generating DTM (CSF + griddata nearest)…")
                dtm_array, gt, proj_wkt = self.generate_dtm_csf_pdal(laz_path, dsm_path, csf_params)
                self.save_raster_qgis(dtm_array, dtm_path, gt, proj_wkt)

                step(4, "Step 4/7 — Computing nDHM (DSM − DTM, exact port of Lasb.generate_ndhm)…")
                # Read both from disk in same bottom-up orientation (positive Y step).
                # Both have same orientation so row-by-row subtraction is geographically correct.
                # NO alignment needed — DTM linspace grid ≈ DSM arange grid for nearest interp.
                # NO clipping — Lasb.generate_ndhm does raw ndhm = dsm - dtm with no manipulation.
                # Clipping to 0 was causing wrong statistics by diluting building heights + destroying gradients.
                ds = gdal.Open(dsm_path)
                dsm_array = ds.GetRasterBand(1).ReadAsArray().astype(np.float32); ds = None
                ndhm = dsm_array - dtm_array   # raw subtraction, exact port of Lasb.generate_ndhm
                self.save_raster_qgis(ndhm, ndhm_path, gt, proj_wkt)

            # Steps from here are the same whether rasters were skipped or not
            offset = 1 if SKIP_RASTERS else 4

            step(offset + 1, f"Step {offset+1}/{total_steps} — Analysing height distribution…")
            alphashape_h_thresh, filter_h_thresh, tri_thresh = self.analyze_low_res_ndhm(ndhm, ndhm_path=ndhm_path)

            step(offset + 2, f"Step {offset+2}/{total_steps} — Extracting building candidates…")
            out_json = os.path.join(out_dir, "buildings_filtered.geojson")

            self.extract_and_filter(
                ndhm, dsm_array, gt, proj_wkt,
                alpha=ALPHA_VAL,
                alphashape_h_thresh=alphashape_h_thresh,
                filter_h_thresh=filter_h_thresh,
                tri_thresh=tri_thresh,
                min_size=MIN_SIZE,
                max_size=MAX_SIZE,
                sq_thresh=SQUARE_THRESH,
                w_thresh=WIDTH_THRESH,
                kernel_size=KERNEL_SIZE,
                out_path=out_json,
                height_var_thresh=HEIGHT_VAR_THRESH,
                convex_hull_ratio_min=CONVEX_HULL_RATIO_MIN,
                max_elongation=MAX_ELONGATION,
                use_per_component=USE_PER_COMPONENT,
                epsg_code=EPSG_CODE,
            )

            step(total_steps, f"Done — output saved to {os.path.basename(out_dir)}")
            progress.close()

            self.iface.messageBar().pushMessage(
                "LasBuildSeg Complete",
                f"Done! Thresholds: AlphaShape={alphashape_h_thresh:.2f}m, Filter={filter_h_thresh:.2f}m. Output CRS: EPSG:3857",
                level=Qgis.Success,
                duration=10
            )

        except Exception as e:
            try:
                progress.close()
            except Exception:
                pass
            self.iface.messageBar().pushMessage("Error", f"{str(e)}", level=Qgis.Critical)
            import traceback
            traceback.print_exc()
            QgsMessageLog.logMessage(traceback.format_exc(), "LasBuildSeg", level=Qgis.Critical)